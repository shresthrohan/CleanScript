"""Benchmark worker: runs ONE engine on ONE dataset in a fresh process and prints JSON.

Every engine performs the same cleaning job (the program in run_benchmark.PROGRAM):
read CSV -> dedupe -> fill AGE median / MARKS mean / CITY mode -> drop column ->
filter STATUS == "ACTIVE" and AGE >= 18 -> min-max normalize MARKS -> rename -> stable sort DESC -> write CSV.

    python engines.py <engine> <data_dir> <rows> <repeats>

Engines:
  cleanscript    the project's real pipeline: read_csv_bytes -> compile_source -> execute (IR interpreter) -> to_csv
  pandas_script  the Pandas script generated by the CleanScript compiler, run as a plain script would be
  python_csv     hand-written pure-Python script (stdlib csv/statistics), the "no library" baseline
  sqlite         hand-written SQL in an in-memory SQLite database (stdlib sqlite3), the "SQL cleaning" baseline
"""
from __future__ import annotations

import time

T_PROCESS = time.perf_counter()  # before any heavy import, to measure import cost

import csv
import gc
import json
import math
import os
import statistics
import sys
from collections import Counter
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1] / "backend"


# -- memory (OS-level, so NumPy/Pandas/SQLite allocations are all counted) -------------

if sys.platform == "win32":
    import ctypes
    from ctypes import wintypes

    class _PMC(ctypes.Structure):
        _fields_ = [("cb", wintypes.DWORD), ("PageFaultCount", wintypes.DWORD),
                    ("PeakWorkingSetSize", ctypes.c_size_t), ("WorkingSetSize", ctypes.c_size_t),
                    ("QuotaPeakPagedPoolUsage", ctypes.c_size_t), ("QuotaPagedPoolUsage", ctypes.c_size_t),
                    ("QuotaPeakNonPagedPoolUsage", ctypes.c_size_t), ("QuotaNonPagedPoolUsage", ctypes.c_size_t),
                    ("PagefileUsage", ctypes.c_size_t), ("PeakPagefileUsage", ctypes.c_size_t)]

    _k32 = ctypes.WinDLL("kernel32")
    _k32.GetCurrentProcess.restype = wintypes.HANDLE
    _psapi = ctypes.WinDLL("psapi")
    _psapi.GetProcessMemoryInfo.argtypes = [wintypes.HANDLE, ctypes.POINTER(_PMC), wintypes.DWORD]

    def memory() -> tuple[int, int]:
        """(current working set, peak working set) in bytes."""
        c = _PMC()
        c.cb = ctypes.sizeof(_PMC)
        _psapi.GetProcessMemoryInfo(_k32.GetCurrentProcess(), ctypes.byref(c), c.cb)
        return c.WorkingSetSize, c.PeakWorkingSetSize
else:
    import resource

    def memory() -> tuple[int, int]:
        with open("/proc/self/statm") as f:
            current = int(f.read().split()[1]) * os.sysconf("SC_PAGE_SIZE")
        return current, resource.getrusage(resource.RUSAGE_SELF).ru_maxrss * 1024


# -- engines: each returns a dict of stage timings (seconds) -----------------------------

def setup_cleanscript(data_dir: Path, rows: int):
    sys.path.insert(0, str(BACKEND))
    from app.compiler import compile_source
    from app.services.dataset_profiler import read_csv_bytes, schema_of
    from app.services.executor import execute

    src = data_dir / f"messy_{rows}.csv"
    dst = data_dir / f"cleanscript_cleaned_{rows}.csv"
    program = (data_dir / f"program_{rows}.clean").read_text(encoding="utf-8")

    def run():
        t0 = time.perf_counter()
        df = read_csv_bytes(src.read_bytes())
        t1 = time.perf_counter()
        schema = schema_of(df)  # scans the data once (types + nulls); the compiler only sees this
        t2 = time.perf_counter()
        report = compile_source(program, schema, src.name)
        t3 = time.perf_counter()
        if report["status"] != "success":
            raise RuntimeError(f"compile failed: {report['diagnostics']}")
        result = execute(df, report["ir"])
        t4 = time.perf_counter()
        if result.status != "success":
            raise RuntimeError(f"execution failed: {result.error}")
        result.dataframe.to_csv(dst, index=False, lineterminator="\n")
        t5 = time.perf_counter()
        return {"read_csv": t1 - t0, "schema": t2 - t1, "compile": t3 - t2, "execute": t4 - t3, "write_csv": t5 - t4}
    return run


def setup_pandas_script(data_dir: Path, rows: int):
    sys.path.insert(0, str(BACKEND))
    import pandas  # noqa: F401  (import cost belongs to setup, like the other engines)
    from app.compiler import compile_source
    from app.services.dataset_profiler import read_csv_bytes, schema_of

    src = data_dir / f"messy_{rows}.csv"
    program = (data_dir / f"program_{rows}.clean").read_text(encoding="utf-8")
    report = compile_source(program, schema_of(read_csv_bytes(src.read_bytes())), src.name)
    code = compile(report["generated_code"], f"generated_{rows}.py", "exec")  # not timed
    os.chdir(data_dir)  # the generated script uses the managed relative filenames

    def run():
        t0 = time.perf_counter()
        exec(code, {"__name__": "__main__"})  # benchmark-only: our compiler's own output for a fixed program
        return {"total": time.perf_counter() - t0}
    return run


def setup_python_csv(data_dir: Path, rows: int):
    src = data_dir / f"messy_{rows}.csv"
    dst = data_dir / f"python_csv_cleaned_{rows}.csv"

    def num(v, cast):
        return None if v == "" else cast(v)

    def run():
        t0 = time.perf_counter()
        with open(src, newline="", encoding="utf-8") as f:
            reader = csv.reader(f)
            next(reader)
            # ID, NAME, AGE, MARKS, STATUS, CITY, HOME ADDRESS ; empty field = missing
            data = [(int(r[0]), r[1] or None, num(r[2], int), num(r[3], float), r[4] or None,
                     r[5] or None, r[6] or None) for r in reader]
        seen = set()
        data = [r for r in data if not (r in seen or seen.add(r))]               # REMOVE_DUPLICATES
        median = statistics.median([r[2] for r in data if r[2] is not None])     # FILL AGE MEDIAN
        median = int(median) if float(median).is_integer() else float(median)
        marks = [r[3] for r in data if r[3] is not None]
        mean = math.fsum(marks) / len(marks)                                     # FILL MARKS MEAN
        mode = Counter(r[5] for r in data if r[5] is not None).most_common(1)[0][0]  # ties: first seen
        out = []
        for i, n, a, m, s, c, _addr in data:                                     # DROP "HOME ADDRESS"
            a = median if a is None else a
            if s == "ACTIVE" and a >= 18:                                        # FILTERs
                out.append([i, n, a, mean if m is None else m, s, mode if c is None else c])
        lo, hi = min(r[3] for r in out), max(r[3] for r in out)                  # NORMALIZE
        for r in out:
            r[3] = 0.0 if hi == lo else (r[3] - lo) / (hi - lo)
        out.sort(key=lambda r: r[3], reverse=True)                               # stable SORT DESC
        with open(dst, "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f, lineterminator="\n")
            w.writerow(["ID", "NAME", "AGE", "SCORE", "STATUS", "CITY"])        # RENAME MARKS TO SCORE
            w.writerows(out)
        return {"total": time.perf_counter() - t0}
    return run


def setup_sqlite(data_dir: Path, rows: int):
    import sqlite3
    src = data_dir / f"messy_{rows}.csv"
    dst = data_dir / f"sqlite_cleaned_{rows}.csv"
    cols = "ID, NAME, AGE, MARKS, STATUS, CITY, ADDR"

    def run():
        t0 = time.perf_counter()
        con = sqlite3.connect(":memory:")
        con.execute("CREATE TABLE raw (ID INTEGER, NAME TEXT, AGE INTEGER, MARKS REAL, STATUS TEXT, CITY TEXT, ADDR TEXT)")
        with open(src, newline="", encoding="utf-8") as f:
            reader = csv.reader(f)
            next(reader)
            con.executemany("INSERT INTO raw VALUES (?,?,?,?,?,?,?)",
                            ([v if v != "" else None for v in r] for r in reader))
        t1 = time.perf_counter()
        con.executescript(f"""
            CREATE TABLE t AS SELECT {cols} FROM raw
              WHERE rowid IN (SELECT MIN(rowid) FROM raw GROUP BY {cols}) ORDER BY rowid;
        """)
        (median,) = con.execute("""
            SELECT AVG(AGE) FROM (SELECT AGE FROM t WHERE AGE IS NOT NULL ORDER BY AGE
              LIMIT 2 - (SELECT COUNT(AGE) FROM t) % 2 OFFSET (SELECT (COUNT(AGE) - 1) / 2 FROM t))
        """).fetchone()
        median = int(median) if float(median).is_integer() else median
        (mean,) = con.execute("SELECT AVG(MARKS) FROM t").fetchone()
        (mode,) = con.execute("""SELECT CITY FROM t WHERE CITY IS NOT NULL GROUP BY CITY
                                 ORDER BY COUNT(*) DESC, MIN(rowid) LIMIT 1""").fetchone()
        con.execute("UPDATE t SET AGE = ? WHERE AGE IS NULL", (median,))
        con.execute("UPDATE t SET MARKS = ? WHERE MARKS IS NULL", (mean,))
        con.execute("UPDATE t SET CITY = ? WHERE CITY IS NULL", (mode,))
        con.execute("DELETE FROM t WHERE STATUS IS NULL OR STATUS != 'ACTIVE' OR AGE IS NULL OR AGE < 18")
        lo, hi = con.execute("SELECT MIN(MARKS), MAX(MARKS) FROM t").fetchone()
        if hi == lo:
            con.execute("UPDATE t SET MARKS = 0.0")
        else:
            con.execute("UPDATE t SET MARKS = (MARKS - ?) / (? - ?)", (lo, hi, lo))
        result = con.execute("SELECT ID, NAME, AGE, MARKS, STATUS, CITY FROM t ORDER BY MARKS DESC, rowid")
        t2 = time.perf_counter()
        with open(dst, "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f, lineterminator="\n")
            w.writerow(["ID", "NAME", "AGE", "SCORE", "STATUS", "CITY"])
            w.writerows(result)
        con.close()
        t3 = time.perf_counter()
        return {"load": t1 - t0, "clean_sql": t2 - t1, "write_csv": t3 - t2, "total": t3 - t0}
    return run


ENGINES = {"cleanscript": setup_cleanscript, "pandas_script": setup_pandas_script,
           "python_csv": setup_python_csv, "sqlite": setup_sqlite}


def main() -> None:
    engine, data_dir, rows, repeats = sys.argv[1], Path(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4])
    run = ENGINES[engine](data_dir, rows)
    import_s = time.perf_counter() - T_PROCESS
    gc.collect()
    mem_ready, _ = memory()

    runs = []
    for _ in range(repeats):
        stages = run()
        stages.setdefault("total", sum(stages.values()))
        runs.append(stages)
        gc.collect()
    mem_now, mem_peak = memory()

    print(json.dumps({
        "engine": engine, "rows": rows, "repeats": repeats,
        "setup_and_import_s": import_s,
        "runs": runs,
        "memory_after_imports_bytes": mem_ready,
        "memory_peak_bytes": mem_peak,
        "memory_end_bytes": mem_now,
    }))


if __name__ == "__main__":
    main()
