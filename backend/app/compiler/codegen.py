"""Code generation: validated IR -> readable, deterministic Python/Pandas source.

The generated program is for inspection; the application runs the same IR through the
restricted interpreter in app/services/executor.py, which implements identical semantics.
All user-supplied text (column names, string literals, file names) is emitted with repr(),
which always yields a valid, properly escaped Python string literal.
"""
from __future__ import annotations

from .ir import DIRECTIONS, OPERATORS, STRATEGIES


def _q(value) -> str:
    return repr(value)


def _no_values_guard(col: str, command: str) -> str:
    return (f"if df[{_q(col)}].isna().all():\n"
            f"    raise ValueError({_q(f'{command}: column {col!r} has no non-null values')})")


def _emit(instr: dict) -> list[str]:
    op = instr["op"]
    col = instr.get("column")
    c = _q(col) if col is not None else None
    if op == "remove_nulls":
        return ["df = df.dropna(how='any')"]
    if op == "remove_duplicates":
        return ["df = df.drop_duplicates(keep='first')"]
    if op == "fill_nulls":
        strategy = instr["strategy"]
        assert strategy in STRATEGIES
        lines = [_no_values_guard(col, "FILL_NULLS")]
        if strategy == "MODE":
            lines += [
                f"non_null = df[{c}].dropna()",
                "counts = non_null.map(non_null.value_counts())",
                "fill_value = non_null[counts == counts.max()].iloc[0]  # ties: first in row order",
            ]
        else:
            lines += [
                f"fill_value = df[{c}].{strategy.lower()}()",
                f"if pd.api.types.is_integer_dtype(df[{c}]) and not float(fill_value).is_integer():",
                f"    df[{c}] = df[{c}].astype('Float64')",
            ]
        lines.append(f"df[{c}] = df[{c}].fillna(fill_value)")
        return lines
    if op == "drop_column":
        return [f"df = df.drop(columns=[{c}])"]
    if op == "rename_column":
        return [f"df = df.rename(columns={{{c}: {_q(instr['new_name'])}}})"]
    if op == "filter_rows":
        operator = instr["operator"]
        assert operator in OPERATORS
        return [f"df = df[df[{c}].notna() & (df[{c}] {operator} {_q(instr['value'])})]  # nulls never match"]
    if op == "normalize":
        return [
            _no_values_guard(col, "NORMALIZE"),
            f"values = df[{c}].astype('Float64')",
            "col_min, col_max = values.min(), values.max()",
            "if col_max == col_min:",
            f"    df[{c}] = values.where(values.isna(), 0.0)  # constant column -> 0.0",
            "else:",
            f"    df[{c}] = (values - col_min) / (col_max - col_min)",
        ]
    if op == "sort_rows":
        direction = instr["direction"]
        assert direction in DIRECTIONS
        return [f"df = df.sort_values({c}, ascending={direction == 'ASC'}, kind='stable', na_position='last')"]
    raise ValueError(f"No code generation rule for op {op!r}")


def _describe(instr: dict) -> str:
    op = instr["op"]
    col = instr.get("column")
    return {
        "remove_nulls": "REMOVE_NULLS",
        "remove_duplicates": "REMOVE_DUPLICATES",
        "fill_nulls": f"FILL_NULLS {col!r} USING {instr.get('strategy')}",
        "drop_column": f"DROP_COLUMN {col!r}",
        "rename_column": f"RENAME {col!r} TO {instr.get('new_name')!r}",
        "filter_rows": f"FILTER {col!r} {instr.get('operator')} {instr.get('value')!r}",
        "normalize": f"NORMALIZE {col!r}",
        "sort_rows": f"SORT {col!r} {instr.get('direction')}",
    }[op]


def generate_code(ir: dict) -> str:
    out = [
        "# Generated by the CleanScript compiler from validated IR.",
        "# CleanScript itself runs the IR through a restricted interpreter with the same",
        "# semantics; this script is the equivalent Pandas program, shown for inspection.",
        "import pandas as pd",
        "",
        f"# LOAD {ir['input']!r} (the managed upload for this session)",
        f"df = pd.read_csv({_q(ir['input'])}, dtype_backend='numpy_nullable')",
    ]
    for instr in ir["instructions"]:
        line = instr.get("source", {}).get("line")
        out += ["", f"# [{instr['index'] + 1}] {_describe(instr)}" + (f"  (line {line})" if line else "")]
        for chunk in _emit(instr):
            out += chunk.split("\n")
    out += ["", f"# SAVE {ir['output']!r}", f"df.to_csv({_q(ir['output'])}, index=False, lineterminator='\\n')", ""]
    return "\n".join(out)
